	private static CardSeed parse(String raw) {
		String[] tokens = raw.split("\\|", -1);
		return new CardSeed(
			LocalDateTime.parse(tokens[0]),
			Long.parseLong(tokens[1]),
			Integer.parseInt(tokens[2]),
			tokens[3],
			Long.parseLong(tokens[4]),
			tokens[5],
			tokens[6]
		);
	}

